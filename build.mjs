// Generates every page from content.mjs: `node build.mjs`.
// Outputs: index.html, services/<slug>/index.html, sitemap.xml, llms.txt, robots.txt.
import { mkdirSync, writeFileSync } from 'node:fs';
import { SITE, lab, services, faqs } from './content.mjs';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const ld = obj => `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, '\\u003c')}</script>`;
const svcUrl = s => `/services/${s.slug}/`;
const LAB_ID = `${SITE}/#lab`;
const ext = 'target="_blank" rel="noopener"';

// ---------- structured data ----------
const labLd = {
  '@type': 'LocalBusiness',
  '@id': LAB_ID,
  additionalType: 'http://www.productontology.org/id/Dental_laboratory',
  name: lab.name,
  alternateName: [lab.short, 'UDL'],
  slogan: lab.tagline,
  description: lab.summary,
  url: `${SITE}/`,
  image: `${SITE}/assets/img/hero.jpg`,
  telephone: lab.phoneIntl,
  email: lab.email,
  address: { '@type': 'PostalAddress', streetAddress: lab.street, addressLocality: lab.suburb, addressRegion: lab.city, postalCode: lab.postcode, addressCountry: 'NZ' },
  areaServed: [{ '@type': 'City', name: 'Auckland' }, { '@type': 'Country', name: 'New Zealand' }],
  knowsAbout: [...services.map(s => s.title), 'Zirconia', 'IPS e.max', 'CAD/CAM', 'Digital Smile Design', ...lab.scanners],
  hasOfferCatalog: {
    '@type': 'OfferCatalog',
    name: 'Dental laboratory services',
    itemListElement: services.map(s => ({ '@type': 'Offer', itemOffered: { '@type': 'Service', name: s.title, url: SITE + svcUrl(s) } })),
  },
};
const faqLd = list => ({ '@type': 'FAQPage', mainEntity: list.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })) });

// ---------- shared chrome ----------
function head({ title, desc, path, image, preload = '', graph }) {
  return `<!doctype html>
<!-- Generated by build.mjs from content.mjs. Edit those, not this file. -->
<html lang="en-NZ">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <link rel="canonical" href="${SITE}${path}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${esc(lab.name)}">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${SITE}${path}">
  <meta property="og:image" content="${SITE}${image}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="theme-color" content="#fafaf8">
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="preload" href="/assets/fonts/anton.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="/assets/fonts/inter.woff2" as="font" type="font/woff2" crossorigin>
  ${preload}
  <link rel="stylesheet" href="/styles.css">
  <script type="module" src="/app.js"></script>
  ${ld({ '@context': 'https://schema.org', '@graph': graph })}
</head>`;
}

