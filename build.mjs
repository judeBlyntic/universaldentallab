// ---------- write ----------
const today = new Date().toISOString().slice(0, 10);
const write = (file, text) => { writeFileSync(file, text); console.log('wrote', file); };

write('index.html', home);
for (const s of services) {
  mkdirSync(`services/${s.slug}`, { recursive: true });
  write(`services/${s.slug}/index.html`, servicePage(s));
}

write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${['/', ...services.map(svcUrl)].map(p => `  <url><loc>${SITE}${p}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);

// AI crawlers are named explicitly so the intent is unambiguous, even though `*` already allows them.
const aiBots = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'Claude-User', 'Google-Extended', 'PerplexityBot', 'Perplexity-User', 'Applebot-Extended', 'Bingbot'];
write('robots.txt', `User-agent: *
Allow: /

${aiBots.map(b => `User-agent: ${b}\nAllow: /`).join('\n\n')}

Sitemap: ${SITE}/sitemap.xml
`);

